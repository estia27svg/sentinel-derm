  const DICTIONARIES = { en, sq, it, de, es };
  const STORAGE_KEY = "sentinel-derm-lang";
  const listeners = [];
  let current = "en";

  function interpolate(template, params) {
    return String(template).replace(/\{(\w+)\}/g, (match, key) =>
      Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match
    );
  }

  function t(key, params = {}) {
    const table = DICTIONARIES[current] || en;
    const template = table[key] ?? en[key] ?? key;
    return interpolate(template, params);
  }

  function locale() {
    return LOCALES[current] || "en-GB";
  }

  function number(value, digits = 0) {
    if (value === null || value === undefined || Number.isNaN(value)) return "--";
    return new Intl.NumberFormat(locale(), {
      minimumFractionDigits: digits,
      maximumFractionDigits: digits,
    }).format(value);
  }

  function percent(value, digits = 1) {
    if (value === null || value === undefined || Number.isNaN(value)) return "--";
    const amount = value * 100;
    const gap = current === "en" ? "" : "\u00A0";
    if (digits === 0 && amount > 0 && amount < 1) return `<1${gap}%`;
    return `${number(amount, digits)}${gap}%`;
  }

  function list(items) {
    try {
      return new Intl.ListFormat(locale(), { style: "long", type: "conjunction" }).format(items);
    } catch (error) {
      return items.join(", ");
    }
  }

  function formatDate(value) {
    const date = new Date(value);
    if (Number.isNaN(date.getTime())) return "--";
    return new Intl.DateTimeFormat(locale(), { day: "2-digit", month: "short", year: "numeric" }).format(date);
  }

  function applyTranslations(root = document) {
    root.querySelectorAll("[data-i18n]").forEach((element) => {
      element.textContent = t(element.dataset.i18n);
    });
    root.querySelectorAll("[data-i18n-html]").forEach((element) => {
      element.innerHTML = t(element.dataset.i18nHtml);
    });
    root.querySelectorAll("[data-i18n-alt]").forEach((element) => {
      element.setAttribute("alt", t(element.dataset.i18nAlt));
    });
    root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
      element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder));
    });
    root.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
      element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel));
    });
    root.querySelectorAll("[data-i18n-title]").forEach((element) => {
      element.setAttribute("title", t(element.dataset.i18nTitle));
    });
    document.title = t("meta.title");
    const description = document.querySelector('meta[name="description"]');
    if (description) description.setAttribute("content", t("meta.description"));
  }

  function normalize(code) {
    const value = String(code || "").toLowerCase().slice(0, 2);
    return DICTIONARIES[value] ? value : "en";
  }

  function setLanguage(code, options = {}) {
    current = normalize(code);
    document.documentElement.lang = current;
    try {
      localStorage.setItem(STORAGE_KEY, current);
    } catch (error) {
      /* storage may be unavailable in private mode */
    }
    if (!options.silent) {
      applyTranslations(document);
      listeners.forEach((listener) => listener(current));
    }
  }

  function detectLanguage() {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (stored) return normalize(stored);
    } catch (error) {
      /* ignore */
    }
    const candidates = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language];
    for (const candidate of candidates) {
      const value = String(candidate || "").toLowerCase().slice(0, 2);
      if (DICTIONARIES[value]) return value;
    }
    return "en";
  }

  function onChange(listener) {
    listeners.push(listener);
  }

  window.SentinelI18N = {
    LANGUAGES,
    t,
    number,
    percent,
    list,
    formatDate,
    applyTranslations,
    setLanguage,
    detectLanguage,
    onChange,
    getLanguage: () => current,
    locale,
  };
